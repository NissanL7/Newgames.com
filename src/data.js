export function getSeedComments(videoId) {
  const seed = [...videoId].reduce((sum, char) => sum + char.charCodeAt(0), 0);
  return Array.from({ length: 4 }, (_, index) => {
    const author = commentAuthors[(seed + index * 2) % commentAuthors.length];
    return {
      id: `seed-${videoId}-${index}`,
      author: author.name,
      handle: author.handle,
      color: author.color,
      text: commentTexts[(seed + index) % commentTexts.length],
      likes: 18 + ((seed * (index + 3)) % 920),
      createdAt: index === 0 ? '2 days ago' : `${index + 1} weeks ago`,
    };
  });
}

